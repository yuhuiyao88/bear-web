(() => {
  const STARTERS = [
    "How do I check assumptions for a linear regression model?",
    "What is the difference between a t-test and an ANOVA?",
    "Why do we use the Central Limit Theorem in statistics?",
    "How can I interpret an odds ratio in logistic regression?",
    "Can you visualize the relationship between two variables?",
  ];

  const $ = (id) => document.getElementById(id);
  const messagesEl = $("messages"), welcome = $("welcome");
  const input = $("input"), sendBtn = $("send"), newChatBtn = $("newChat");

  let history = []; // {role: "user"|"model", text}
  let busy = false;

  // ---------- starters ----------
  const startersEl = $("starters");
  for (const s of STARTERS) {
    const b = document.createElement("button");
    b.type = "button";
    b.className = "starter";
    b.textContent = s;
    b.addEventListener("click", () => send(s));
    startersEl.appendChild(b);
  }

  // ---------- rendering ----------
  marked.setOptions({ gfm: true, breaks: false });

  function renderMarkdown(text) {
    // Protect math from the Markdown parser, render it with KaTeX afterwards.
    const math = [];
    const stash = (tex, display) => {
      math.push({ tex, display });
      return `@@MATH${math.length - 1}@@`;
    };
    let src = text
      .replace(/\$\$([\s\S]+?)\$\$/g, (_, t) => stash(t, true))
      .replace(/\\\[([\s\S]+?)\\\]/g, (_, t) => stash(t, true))
      .replace(/\\\(([\s\S]+?)\\\)/g, (_, t) => stash(t, false))
      .replace(/(^|[^\\$\d])\$([^\s$](?:[^$\n]*?[^\s$])?)\$(?!\d)/g, (_, pre, t) => pre + stash(t, false));
    let html = DOMPurify.sanitize(marked.parse(src));
    html = html.replace(/@@MATH(\d+)@@/g, (_, i) => {
      const m = math[+i];
      try {
        return katex.renderToString(m.tex, { displayMode: m.display, throwOnError: false });
      } catch (e) {
        return m.tex;
      }
    });
    return html;
  }

  function addUser(text) {
    welcome.hidden = true;
    const div = document.createElement("div");
    div.className = "msg user";
    div.textContent = text;
    messagesEl.appendChild(div);
    scroll();
  }

  function addBear() {
    welcome.hidden = true;
    const wrap = document.createElement("div");
    wrap.className = "msg bear";
    wrap.innerHTML = '<img class="avatar" src="bear-128.png" alt="" width="28" height="28"><div class="body"><p class="thinking">BEAR is thinking</p></div>';
    messagesEl.appendChild(wrap);
    scroll();
    return wrap.querySelector(".body");
  }

  function fillBear(body, data) {
    body.innerHTML = renderMarkdown(data.text || "");
    for (const src of data.images || []) {
      const img = document.createElement("img");
      img.className = "plot";
      img.src = src;
      img.alt = "Plot generated by BEAR";
      body.appendChild(img);
    }
    if (data.sources && data.sources.length) {
      const d = document.createElement("details");
      d.className = "sources";
      d.innerHTML = "<summary>Course readings consulted</summary>";
      const ul = document.createElement("ul");
      for (const s of data.sources) {
        const li = document.createElement("li");
        const a = document.createElement("a");
        a.href = s.url;
        a.target = "_blank";
        a.rel = "noopener";
        a.textContent = s.source;
        li.appendChild(a);
        li.appendChild(document.createTextNode(` · ${s.section}${s.page ? ` (PDF p. ${s.page})` : ""}`));
        ul.appendChild(li);
      }
      d.appendChild(ul);
      body.appendChild(d);
    }
    scroll();
  }

  function showError(body, message, retry) {
    body.innerHTML = "";
    const p = document.createElement("p");
    p.className = "error";
    p.textContent = message;
    if (retry) {
      const b = document.createElement("button");
      b.type = "button";
      b.className = "ghost";
      b.textContent = "Try again";
      b.addEventListener("click", () => {
        body.closest(".msg").remove();
        request();
      });
      p.appendChild(b);
    }
    body.appendChild(p);
  }

  function scroll() {
    messagesEl.scrollTop = messagesEl.scrollHeight;
  }

  // ---------- sending ----------
  async function send(text) {
    text = (text || "").trim();
    if (!text || busy) return;
    // Drop a question whose answer failed, so turns keep alternating.
    if (history.length && history[history.length - 1].role === "user") history.pop();
    addUser(text);
    history.push({ role: "user", text });
    input.value = "";
    autosize();
    await request();
  }

  async function request() {
    busy = true;
    sendBtn.disabled = true;
    const body = addBear();
    try {
      const r = await fetch("/api/chat", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ messages: history }),
        signal: AbortSignal.timeout(90000),
      });
      const data = await r.json().catch(() => ({}));
      if (!r.ok) {
        showError(body, data.error || "Something went wrong.", true);
      } else {
        fillBear(body, data);
        history.push({ role: "model", text: data.text || "" });
      }
    } catch (e) {
      showError(body, e && e.name === "TimeoutError"
        ? "BEAR is taking too long right now. Please try again in a minute."
        : "Couldn't reach BEAR. Check your connection.", true);
    } finally {
      busy = false;
      sendBtn.disabled = false;
      input.focus();
    }
  }

  $("composer").addEventListener("submit", (e) => {
    e.preventDefault();
    send(input.value);
  });
  input.addEventListener("keydown", (e) => {
    if (e.key === "Enter" && !e.shiftKey && !e.isComposing) {
      e.preventDefault();
      send(input.value);
    }
  });
  function autosize() {
    input.style.height = "auto";
    input.style.height = Math.min(input.scrollHeight, 200) + "px";
  }
  input.addEventListener("input", autosize);

  newChatBtn.addEventListener("click", () => {
    if (busy) return;
    history = [];
    messagesEl.querySelectorAll(".msg").forEach((m) => m.remove());
    welcome.hidden = false;
    input.focus();
  });

  input.focus();
})();
